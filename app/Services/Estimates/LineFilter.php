<?php

declare(strict_types=1);

namespace App\Services\Estimates;

/**
 * Отсеивает «строки», которые на деле — мусор разбора: заголовки листов
 * («ЭКСПЛИКАЦИЯ»), куски перенесённых наименований («регистрации программы»),
 * колонка завода-изготовителя («ТД «ТИНКО»»), голые артикулы («PR03.0072»)
 * и строки, где в колонку единицы попали цифры штампа.
 */
class LineFilter
{
    /** Заголовки и служебные слова спецификаций и штампов. */
    private const HEADERS = ['экспликация', 'спецификация', 'ведомость', 'примечание', 'примечания', 'наименование', 'обозначение', 'формат', 'лист', 'листов', 'разработал', 'проверил', 'н.контр', 'утвердил', 'изм', 'стадия'];

    /** Организационно-правовые формы: так начинается колонка «Завод-изготовитель». */
    private const VENDOR = '/^(тд|оао|ооо|зао|пао|ао|ип|нпо|нпп|гк|торговый дом)(\s|«|"|$)/u';

    public function isJunk(string $name, ?string $unit): bool
    {
        $name = trim(preg_replace('/\s+/u', ' ', $name) ?? '');
        $lower = mb_strtolower($name);

        // Хотя бы одно слово из трёх букв подряд: «PR03.0072» — артикул без наименования.
        if (preg_match('/\p{L}{3,}/u', $name) !== 1) {
            return true;
        }

        if (in_array(rtrim($lower, ' .:'), self::HEADERS, true) || preg_match(self::VENDOR, $lower) === 1) {
            return true;
        }

        // Одно слово заглавными без цифр и дефисов — заголовок («ЭКСПЛИКАЦИЯ»), не марка («АКОР-УОП»).
        if (preg_match('/^\p{Lu}{6,}$/u', $name) === 1) {
            return true;
        }

        // Кусок перенесённой строки: начинается со строчной буквы и короткий.
        if (preg_match('/^\p{Ll}/u', $name) === 1 && count(explode(' ', $name)) <= 3) {
            return true;
        }

        // В колонку единицы попали цифры штампа: «828 383 838 384 Г».
        $unit = trim((string) $unit);

        return mb_strlen($unit) > 20 || preg_match('/\d{3}\D+\d{3}/u', $unit) === 1;
    }
}
