<?php

declare(strict_types=1);

namespace Tests\Unit;

use App\Services\Estimates\ExtractedLine;
use App\Services\Estimates\TzDraftExtractor;
use App\Support\Quantity;
use PHPUnit\Framework\TestCase;

class TzDraftExtractorTest extends TestCase
{
    /** Абзацы как в ТЗ на замену троллеев мостовых кранов (25.11.2026), сокращено. */
    public const PARAGRAPHS = [
        'Техническое задание',
        'Краткая характеристика объекта',
        'Характеристики подкранового пути:',
        'Длина подкранового пути – 114 м.',
        'Количество потребителей (кранов) – 3.',
        'Характеристики существующего оборудования:',
        'Шинопровод:',
        'Напряжение – 500 В',
        'Количество проводников – 3-х проводная сеть (3 фазы)',
        'Длина шинопровода – 113 м',
        'Наличие ремонтных зон – 2 по 16 м',
        'Питающий кабель:',
        'Тип кабеля – КВВГ 4х16',
        'Длина – около 75 метров (включая подключение ремонтных зон)',
        'Рубильник:',
        'Количество – 2 шт.',
        'Требования к новому оборудованию',
        'Троллейный шинопровод:',
        'Количество проводников – 4-х проводная сеть (3 фазы + заземление PE)',
        'Длина шинопровода – 114 м (96 м основной участок + 18 м ремонтный участок)',
        'Количество потребителей (кранов) – 3',
        'Количество подвода питания – 2 шт (1 шт для основного участка, 1 шт для ремонтного участка)',
        'Длина ремонтного участка – 18 м',
        'Количество токосъемников – 6 одинарных или 3 двойных',
        'Количество световой индикации напряжения на троллеях – 2 шт',
        'Кабель питания:',
        'Длина общая – около 92 метров (в том числе: от ШР до вводного рубильника около 12 метров)',
        'Рубильник:',
        'Тип рубильника – ЯБПВУ 100 или аналог',
        'Количество – 2 шт.',
        'Состав и содержание работ',
        '- выполнить демонтаж существующего оборудования: открытого троллейного шинопровода, питающего кабеля, рубильников;',
    ];

    public function test_volumes_from_text_of_technical_task(): void
    {
        $lines = array_map(
            fn (ExtractedLine $line): string => $line->name.' | '.$line->unit.' | '.$line->quantityMilli,
            (new TzDraftExtractor)->extract(self::PARAGRAPHS),
        );

        $this->assertSame([
            'Демонтаж: Шинопровод | м | 113000',
            'Демонтаж: Питающий кабель | м | 75000',
            'Демонтаж: Рубильник | шт | 2000',
            'Монтаж: Троллейный шинопровод | м | 114000',
            'Монтаж: Троллейный шинопровод — количество подвода питания | шт | 2000',
            'Монтаж: Троллейный шинопровод — количество токосъемников | шт | 6000',
            'Монтаж: Троллейный шинопровод — количество световой индикации напряжения на троллеях | шт | 2000',
            'Монтаж: Кабель питания | м | 92000',
            'Монтаж: Рубильник | шт | 2000',
        ], $lines);
    }

    public function test_quantity_from_form_without_floats(): void
    {
        $this->assertSame(12_500, Quantity::toMilli('12,5'));
        $this->assertSame(250, Quantity::toMilli('0.25'));
        $this->assertSame(114_000, Quantity::toMilli('114'));
        $this->assertSame(0, preg_match(Quantity::PATTERN, '0'));
        $this->assertSame(0, preg_match(Quantity::PATTERN, '1,2345'));
    }
}
